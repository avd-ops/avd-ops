// Builds site/blog/ (https://avd-ops.dev/blog/) and site/blog/feed.xml from docs/blog/*.md.
// Personal project, not for production, as is; not affiliated with the author's employer or Microsoft.
//
//   node scripts/site/build-blog.mjs           # write site/blog/
//   node scripts/site/build-blog.mjs --check   # fail if site/blog/ is out of date (CI)
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync, realpathSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { marked } from 'marked';
import { applyShell } from './apply-shell.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const SRC_DIR = join(root, 'docs/blog');
const OUT_DIR = join(root, 'site/blog');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function parseFrontMatter(raw) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  const meta = {};
  if (m) {
    for (const line of m[1].split(/\r?\n/)) {
      const kv = line.match(/^(\w[\w-]*):\s*(.+)$/);
      if (!kv) continue;
      const key = kv[1];
      let val = kv[2].trim();
      if (val.startsWith('[') && val.endsWith(']')) {
        meta[key] = val.slice(1, -1).split(',').map((s) => s.trim().replace(/^"(.*)"$/, '$1')).filter(Boolean);
      } else {
        meta[key] = val.replace(/^"(.*)"$/, '$1').replace(/\\"/g, '"');
      }
    }
  }
  return { meta, body: m ? raw.slice(m[0].length) : raw };
}

export function inferAutoTags(slug, body) {
  const tags = new Set();
  if (slug.includes('weekly-digest')) tags.add('weekly-digest');
  else if (slug.includes('daily-update')) tags.add('daily-digest');
  if (/^##\s+Releases\b/m.test(body)) tags.add('release');
  if (/^##\s+Features\b/m.test(body)) tags.add('features');
  if (/^##\s+Findings\b/m.test(body)) tags.add('findings');
  if (/^##\s+Fixes\b/m.test(body)) tags.add('fixes');
  if (!tags.size) tags.add('note');
  return [...tags];
}

export function inferAutoRepos(body, knownRepos) {
  const found = [];
  for (const name of knownRepos) {
    if (new RegExp(`\\b${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`).test(body)) found.push(name);
  }
  return found;
}

export function loadPosts(srcDir = SRC_DIR) {
  if (!existsSync(srcDir)) return [];
  const knownRepos = JSON.parse(readFileSync(join(root, 'repos.json'), 'utf8')).repos.map((r) => r.name);
  const posts = [];
  for (const file of readdirSync(srcDir).sort()) {
    if (!file.endsWith('.md') || file === 'README.md') continue;
    const raw = readFileSync(join(srcDir, file), 'utf8');
    const { meta, body } = parseFrontMatter(raw);
    const slug = file.replace(/\.md$/, '');
    const dateMatch = slug.match(/^(\d{4}-\d{2}-\d{2})/);
    const date = meta.date || (dateMatch ? dateMatch[1] : '1970-01-01');
    const title = meta.title || (body.match(/^# (.+)$/m) || [, slug])[1];
    const summary = meta.summary || '';
    const repos = Array.isArray(meta.repos) && meta.repos.length ? meta.repos : inferAutoRepos(body, knownRepos);
    const tags = Array.isArray(meta.tags) && meta.tags.length ? meta.tags : inferAutoTags(slug, body);
    const cleanBody = body.replace(/^# .+\r?\n+/, '');
    const htmlBody = marked.parse(cleanBody, { gfm: true });
    posts.push({ file, slug, url: `${slug}.html`, date, title, summary, repos, tags, htmlBody });
  }
  posts.sort((a, b) => b.date.localeCompare(a.date) || b.slug.localeCompare(a.slug));
  return posts;
}

function wrapPage({ title, description, current, bodyHtml, extraHead = '' }) {
  const shell = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>${esc(title)} | avd-ops</title>
<meta name="description" content="${esc(description)}">
${extraHead}<!-- shell:head -->
<!-- /shell:head -->
</head>
<body class="shell">
<!-- Generated by scripts/site/build-blog.mjs from docs/blog/. Do not edit; rebuild instead. -->
<!-- shell:top -->
<!-- /shell:top -->
<main id="main" class="roadmap">
${bodyHtml}
</main>
<!-- shell:foot -->
<!-- /shell:foot -->
</body>
</html>
`;
  return applyShell(shell, current);
}

export function buildIndexHtml(posts) {
  const allTags = [...new Set(posts.flatMap((p) => p.tags))].sort();
  const allRepos = [...new Set(posts.flatMap((p) => p.repos))].sort();

  const filtersHtml = posts.length
    ? `<div class="rm-filters" data-blog-filters>
<div class="rm-filter-row" role="group" aria-label="Filter by tag">
<span class="rm-filter-label">Tag</span>
<button class="chip rm-chip-btn" type="button" data-filter-tag="all" aria-pressed="true">All tags</button>
${allTags.map((t) => `<button class="chip rm-chip-btn" type="button" data-filter-tag="${esc(t)}" aria-pressed="false">${esc(t)}</button>`).join('\n')}
</div>
<div class="rm-filter-row" role="group" aria-label="Filter by repo">
<span class="rm-filter-label">Repo</span>
<button class="chip rm-chip-btn" type="button" data-filter-repo="all" aria-pressed="true">All repos</button>
${allRepos.map((r) => `<button class="chip rm-chip-btn mono" type="button" data-filter-repo="${esc(r)}" aria-pressed="false">${esc(r)}</button>`).join('\n')}
</div>
<div class="rm-filter-status" hidden>
<span class="rm-filter-summary" data-filter-summary></span>
<button class="chip rm-chip-btn" type="button" data-filter-reset>Clear filters</button>
</div>
</div>`
    : '';

  const cards = posts.length
    ? posts.map((p) => {
        const repoChips = p.repos.map((r) => `<span class="chip mono">${esc(r)}</span>`).join(' ');
        const tagChips = p.tags.map((t) => `<span class="chip">${esc(t)}</span>`).join(' ');
        return `<article class="card rm-card" id="post-${esc(p.slug)}" data-blog-card data-tags="${esc(p.tags.join(','))}" data-repos="${esc(p.repos.join(','))}">
<div class="rm-top"><span class="chip mono">${esc(p.date)}</span>${repoChips ? ` ${repoChips}` : ''}${tagChips ? ` ${tagChips}` : ''}</div>
<h3><a href="${esc(p.url)}">${esc(p.title)}</a></h3>
${p.summary ? `<p>${esc(p.summary)}</p>` : ''}
</article>`;
      }).join('\n')
    : '<p>No blog posts yet.</p>';

  const bodyHtml = `<p class="eyebrow">Blog &amp; updates</p>
<h1>Major updates, features and findings across avd-ops.</h1>
<p class="lede">Weekly digests drafted from public releases, merged pull requests, accepted issues and decision records across the avd-ops repositories, plus deeper engineering notes.</p>
<p><a class="chip" href="feed.xml">Atom feed (feed.xml)</a></p>
<section aria-labelledby="blog-posts-heading">
<h2 id="blog-posts-heading">Posts</h2>
${filtersHtml}
<div class="rm-list">
${cards}
</div>
</section>`;

  return wrapPage({
    title: 'Blog & updates',
    description: 'Weekly digests of major updates, features and findings across the avd-ops repositories.',
    current: 'blog/index.html',
    extraHead: '<link rel="alternate" type="application/atom+xml" title="avd-ops blog" href="feed.xml">\n<script src="../assets/blog.js" defer></script>\n',
    bodyHtml,
  });
}

export function buildPostHtml(post) {
  const repoChips = post.repos.map((r) => `<span class="chip mono">${esc(r)}</span>`).join(' ');
  const tagChips = post.tags.map((t) => `<span class="chip">${esc(t)}</span>`).join(' ');
  const bodyHtml = `<p class="eyebrow"><a href="index.html">Blog &amp; updates</a> &middot; <span class="mono">${esc(post.date)}</span></p>
<h1>${esc(post.title)}</h1>
${post.summary ? `<p class="lede">${esc(post.summary)}</p>` : ''}
${(repoChips || tagChips) ? `<div class="rm-top">${repoChips}${repoChips && tagChips ? ' ' : ''}${tagChips}</div>` : ''}
<article class="blog-post">
${post.htmlBody}
</article>
<p class="rm-meta"><a href="index.html">Back to all posts</a> &middot; <a href="feed.xml">Atom feed</a></p>`;

  return wrapPage({
    title: post.title,
    description: post.summary || post.title,
    current: `blog/${post.url}`,
    extraHead: '<link rel="alternate" type="application/atom+xml" title="avd-ops blog" href="feed.xml">\n',
    bodyHtml,
  });
}

export function buildFeedXml(posts) {
  const latest = posts.slice(0, 20);
  const updated = latest[0]?.date ? `${latest[0].date}T00:00:00Z` : '2026-01-01T00:00:00Z';
  const entries = latest.map((p) => `  <entry>
    <title>${esc(p.title)}</title>
    <link href="https://avd-ops.dev/blog/${esc(p.url)}"/>
    <id>https://avd-ops.dev/blog/${esc(p.url)}</id>
    <updated>${esc(p.date)}T00:00:00Z</updated>
    <summary>${esc(p.summary || p.title)}</summary>
    <content type="html">${esc(p.htmlBody)}</content>
  </entry>`).join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>avd-ops blog</title>
  <subtitle>Major updates, features and findings across the avd-ops repositories.</subtitle>
  <link href="https://avd-ops.dev/blog/feed.xml" rel="self"/>
  <link href="https://avd-ops.dev/blog/"/>
  <id>https://avd-ops.dev/blog/</id>
  <updated>${esc(updated)}</updated>
${entries}
</feed>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  const check = process.argv.includes('--check');
  const posts = loadPosts();
  const expected = new Map([
    ['index.html', buildIndexHtml(posts)],
    ['feed.xml', buildFeedXml(posts)],
    ...posts.map((p) => [p.url, buildPostHtml(p)]),
  ]);

  if (check) {
    if (!existsSync(OUT_DIR)) {
      console.error('site/blog/ does not exist; run node scripts/site/build-blog.mjs');
      process.exit(1);
    }
    const existingFiles = new Set(readdirSync(OUT_DIR));
    const stale = [];
    for (const [name, content] of expected) {
      const target = join(OUT_DIR, name);
      if (!existsSync(target) || readFileSync(target, 'utf8') !== content) stale.push(name);
      existingFiles.delete(name);
    }
    for (const extra of existingFiles) stale.push(`extra:${extra}`);
    if (stale.length) {
      console.error(`site/blog/ is out of date (${stale.join(', ')}); run node scripts/site/build-blog.mjs`);
      process.exit(1);
    }
    console.log(`site/blog/ is up to date (${posts.length} posts)`);
    process.exit(0);
  }

  mkdirSync(OUT_DIR, { recursive: true });
  for (const existing of readdirSync(OUT_DIR)) {
    if (!expected.has(existing)) rmSync(join(OUT_DIR, existing), { force: true });
  }
  for (const [name, content] of expected) {
    writeFileSync(join(OUT_DIR, name), content);
  }
  console.log(`wrote site/blog/ (${posts.length} posts)`);
}
