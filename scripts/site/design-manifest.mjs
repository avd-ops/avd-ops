// Writes site/assets/MANIFEST.json: the design system's version and a SHA-256 for every file another repo
// vendors (docs/design-system.md, "Take a pinned copy"). A repo that takes a copy records the same hashes in its
// own design-system.lock.json, and its test fails if a vendored file changes by hand.
// Personal project, not for production, as is; not affiliated with the author's employer or Microsoft.
//
//   node scripts/site/design-manifest.mjs           # write the manifest
//   node scripts/site/design-manifest.mjs --check   # fail if it is out of date (CI)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const ASSETS = join(root, 'site/assets');
// What a sibling repo vendors. site.css and graph.js are avd-ops.dev's own.
export const VENDORED = ['avd-ops.css', 'avd-ops-shell.css', 'avd-ops-portal.css', 'theme.js', 'fonts', 'brand'];

const walk = (p) => (statSync(p).isDirectory() ? readdirSync(p).sort().flatMap((f) => walk(join(p, f))) : [p]);

export function manifest() {
  const version = (readFileSync(join(ASSETS, 'avd-ops.css'), 'utf8').match(/^\/\* avd-ops design system v(\d+\.\d+\.\d+) /) || [])[1];
  const files = {};
  for (const f of VENDORED.flatMap((v) => walk(join(ASSETS, v)))) {
    files[relative(ASSETS, f)] = createHash('sha256').update(readFileSync(f)).digest('hex');
  }
  return `${JSON.stringify({ $comment: 'Generated by scripts/site/design-manifest.mjs. Vendor these files at the tag ds-v<version>; see docs/design-system.md.', version, files }, null, 1)}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = join(ASSETS, 'MANIFEST.json');
  const text = manifest();
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
      console.error('site/assets/MANIFEST.json is out of date; run node scripts/site/design-manifest.mjs');
      process.exit(1);
    }
    console.log('the design system manifest is up to date');
  } else {
    writeFileSync(path, text);
    console.log('wrote site/assets/MANIFEST.json');
  }
}
