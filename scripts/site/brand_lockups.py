"""Writes the avd-ops lockups (mark + wordmark + tagline) as pure vector SVG in site/assets/brand/.

The text is converted to outlines from the fonts the design system already serves (site/assets/fonts), so a
lockup looks the same wherever it is used as an image, with no font installed. Run it after changing the mark,
the fonts or the tagline; tests/brand.test.mjs checks the files exist and carry no <text>.
Personal project, not for production, as is; not affiliated with the author's employer or Microsoft.

    pip install fonttools brotli && python3 scripts/site/brand_lockups.py
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "site/assets"
WORD, TAGLINE = "avd-ops", "DEPLOY QUIETLY"
INK, BRAND, ACCENT, SHELL_FG, WHITE = "#0d1015", "#1ca998", "#0b7a6e", "#e8f1f0", "#ffffff"


def outline(font_file, text, size, x, baseline, tracking=0.0):
    """Path data for text set at size (em) with its baseline at y, and the x where it ends."""
    font = TTFont(font_file)
    upm = font["head"].unitsPerEm
    cmap, glyphs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    scale = size / upm
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    for ch in text:
        name = cmap[ord(ch)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += hmtx[name][0] * scale + tracking * size
    return pen.getCommands(), x - tracking * size


def mark_parts(kind):
    """The mark from brand/mark.svg (square) or brand/mark-white.svg (one color), without the outer <svg>."""
    src = (ASSETS / "brand" / ("mark.svg" if kind == "color" else "mark-white.svg")).read_text()
    body = src.split(">", 1)[1].rsplit("</svg>", 1)[0]
    return "\n".join(l for l in body.splitlines() if "<!--" not in l).strip()


def lockup(kind, word_fill, tag_fill, note):
    word, end = outline(ASSETS / "fonts/schibsted-grotesk-latin-700-normal.woff2", WORD, 62, 122, 60)
    # The tagline is tracked out to end where the word ends, as in the original lockup.
    mono = ASSETS / "fonts/jetbrains-mono-latin-600-normal.woff2"
    size = 17
    _, plain_end = outline(mono, TAGLINE, size, 125, 86)
    tracking = (end - plain_end) / (size * (len(TAGLINE) - 1))
    tag, tag_end = outline(mono, TAGLINE, size, 125, 86, tracking=tracking)
    width = round(max(end, tag_end) + 4)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 100" role="img" aria-label="avd-ops, deploy quietly">
  <!-- {note} Generated by scripts/site/brand_lockups.py: text outlined from Schibsted Grotesk 700 and JetBrains Mono 600. -->
  {mark_parts(kind)}
  <path d="{word}" fill="{word_fill}"/>
  <path d="{tag}" fill="{tag_fill}"/>
</svg>
"""


def main():
    out = {
        "lockup.svg": lockup("color", INK, ACCENT, "avd-ops lockup for light backgrounds: the mark, the word in brand ink, the tagline in the readable teal."),
        "lockup-dark.svg": lockup("color", SHELL_FG, BRAND, "avd-ops lockup for dark backgrounds (the brand bar's ink and darker): the mark, the word in the shell's light, the tagline in brand teal."),
        "lockup-white.svg": lockup("white", WHITE, WHITE, "One-color white avd-ops lockup, for photos, slides and anything printed in one color."),
    }
    for name, svg in out.items():
        (ASSETS / "brand" / name).write_text(svg)
        print(f"wrote site/assets/brand/{name}")


if __name__ == "__main__":
    main()
