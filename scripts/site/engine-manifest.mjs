// Writes site/assets/engine/MANIFEST.json: the portal engine's version and, for every engine file, its SHA-256,
// whether it makes requests (network) and the engine files it needs (docs/portal-engine-spec.md, section 4). A
// portal that takes a copy records the hashes of the files it takes in its own engine.lock.json. `released` keeps
// the hashes of each released version, so one version never means two contents (a test checks it).
// Personal project, not for production, as is; not affiliated with the author's employer or Microsoft.
//
//   node scripts/site/engine-manifest.mjs             # write the manifest
//   node scripts/site/engine-manifest.mjs --check     # fail if it is out of date (CI)
//   node scripts/site/engine-manifest.mjs --release   # also record this version's hashes (the release PR)
import { readFileSync, writeFileSync, readdirSync, existsSync, realpathSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const ENGINE = join(root, 'site/assets/engine');
export const PATH = join(ENGINE, 'MANIFEST.json');
// The one file allowed to make requests (section 8).
export const NETWORK = ['probe.js'];

export const engineFiles = () => readdirSync(ENGINE).filter((f) => f.endsWith('.js')).sort();
export const versionOf = (text) => (text.match(/^\/\* avd-ops portal engine v(\d+\.\d+\.\d+): /) || [])[1];

export function manifest(opts = {}) {
  const previous = existsSync(PATH) ? JSON.parse(readFileSync(PATH, 'utf8')) : {};
  const files = {};
  let version;
  for (const f of engineFiles()) {
    const buf = readFileSync(join(ENGINE, f)), text = buf.toString('utf8');
    const v = versionOf(text);
    if (!v) throw new Error(`${f}: no version line`);
    if (version && v !== version) throw new Error(`${f}: v${v}, other files v${version}`);
    version = v;
    const needs = [...new Set([...text.matchAll(/require\('\.\/([\w-]+\.js)'\)/g)].map((m) => m[1]))].sort();
    files[f] = { sha256: createHash('sha256').update(buf).digest('hex'), network: NETWORK.includes(f), needs };
  }
  const released = { ...(previous.released || {}) };
  if (opts.release) {
    const hashes = Object.fromEntries(Object.entries(files).map(([f, e]) => [f, e.sha256]));
    if (released[version] && JSON.stringify(released[version]) !== JSON.stringify(hashes)) throw new Error(`v${version} is released with other contents; bump the version`);
    released[version] = hashes;
  }
  const $comment = 'Generated by scripts/site/engine-manifest.mjs. Vendor these files at the tag pe-v<version>; see docs/portal-engine-spec.md, section 4.';
  return `${JSON.stringify({ $comment, version, files, released }, null, 1)}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  const text = manifest({ release: process.argv.includes('--release') });
  if (process.argv.includes('--check')) {
    if (!existsSync(PATH) || readFileSync(PATH, 'utf8').replace(/\r\n/g, '\n') !== text) {
      console.error('site/assets/engine/MANIFEST.json is out of date; run node scripts/site/engine-manifest.mjs');
      process.exit(1);
    }
    console.log('the engine manifest is up to date');
  } else {
    writeFileSync(PATH, text);
    console.log('wrote site/assets/engine/MANIFEST.json');
  }
}
